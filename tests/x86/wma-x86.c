/* One stage: a WMA V2 bitstream plus the parameters it is DECLARED with.  The
 * declared average byte rate is separate from the real one on purpose -- stage
 * C lies about it the way the Microsoft xWMA encoder does. */
struct wma_stage
{
    const char *name;
    const unsigned char *data;
    unsigned int data_size;
    const unsigned char *extradata;
    unsigned int extradata_size;
    unsigned int rate;
    unsigned int channels;
    unsigned int block_align;
    unsigned int declared_avg_bytes;
    /* 0 pushes the whole bitstream in one ProcessInput; otherwise the stream
     * is pushed in chunks of this many bytes, which is what exercises the unix
     * side's packet FIFO (one push -> several block_align packets, and a
     * remainder carried to the next push). */
    unsigned int push_chunk;
    /* Push one deliberately MISALIGNED buffer first.  wma_decoder.c's
     * transform_ProcessInput drops any sample whose length is not a multiple
     * of block_align -- "WMA transform uses fixed size input samples and
     * ignores samples with invalid sizes" -- so this must be harmless and must
     * not shift the phase of everything that follows. */
    int probe_misaligned;
};

/* A media type carrying everything wma_decoder.c's SetInputType /
 * SetOutputType insist on; MFCreateWaveFormatExFromMFMediaType turns exactly
 * these attributes into the WAVEFORMATEX the unix side reads. */
static HRESULT make_audio_type( IMFMediaType **out, const GUID *subtype,
                                UINT32 channels, UINT32 rate, UINT32 avg_bytes,
                                UINT32 block_align, UINT32 bits,
                                const void *user_data, UINT32 user_data_size )
{
    IMFMediaType *type;
    HRESULT hr;

    if (FAILED(hr = MFCreateMediaType( &type ))) return hr;
    IMFMediaType_SetGUID( type, &MF_MT_MAJOR_TYPE, &MFMediaType_Audio );
    IMFMediaType_SetGUID( type, &MF_MT_SUBTYPE, subtype );
    IMFMediaType_SetUINT32( type, &MF_MT_AUDIO_NUM_CHANNELS, channels );
    IMFMediaType_SetUINT32( type, &MF_MT_AUDIO_SAMPLES_PER_SECOND, rate );
    IMFMediaType_SetUINT32( type, &MF_MT_AUDIO_AVG_BYTES_PER_SECOND, avg_bytes );
    IMFMediaType_SetUINT32( type, &MF_MT_AUDIO_BLOCK_ALIGNMENT, block_align );
    IMFMediaType_SetUINT32( type, &MF_MT_AUDIO_BITS_PER_SAMPLE, bits );
    if (user_data_size)
        IMFMediaType_SetBlob( type, &MF_MT_USER_DATA, (const UINT8 *)user_data, user_data_size );
    *out = type;
    return S_OK;
}

static HRESULT wrap_sample( IMFSample **out, const void *data, DWORD size, DWORD capacity )
{
    IMFMediaBuffer *buffer;
    IMFSample *sample;
    BYTE *dst;
    HRESULT hr;

    if (FAILED(hr = MFCreateMemoryBuffer( capacity, &buffer ))) return hr;
    if (size)
    {
        if (FAILED(hr = IMFMediaBuffer_Lock( buffer, &dst, NULL, NULL )))
        {
            IMFMediaBuffer_Release( buffer );
            return hr;
        }
        memcpy( dst, data, size );
        IMFMediaBuffer_Unlock( buffer );
    }
    IMFMediaBuffer_SetCurrentLength( buffer, size );
    if (FAILED(hr = MFCreateSample( &sample )))
    {
        IMFMediaBuffer_Release( buffer );
        return hr;
    }
    IMFSample_AddBuffer( sample, buffer );
    IMFMediaBuffer_Release( buffer );
    *out = sample;
    return S_OK;
}

static void collect_pcm( IMFSample *sample )
{
    IMFMediaBuffer *buffer;
    DWORD len = 0, i;
    BYTE *data;

    if (FAILED(IMFSample_ConvertToContiguousBuffer( sample, &buffer ))) return;
    if (SUCCEEDED(IMFMediaBuffer_Lock( buffer, &data, NULL, &len )))
    {
        for (i = 0; i + 3 < len; i += 4)   /* 16-bit stereo: take the left channel */
        {
            short v = (short)(data[i] | (data[i + 1] << 8));
            int a = v < 0 ? -(int)v : (int)v;

            if (pcm_samples >= sizeof(pcm) / sizeof(pcm[0])) break;
            pcm[pcm_samples++] = v;
            if ((unsigned int)a > peak_abs) peak_abs = (unsigned int)a;
        }
        IMFMediaBuffer_Unlock( buffer );
    }
    IMFMediaBuffer_Release( buffer );
}

/* Positive-going zero crossings are one per period, so
 * crossings * rate / samples is the fundamental in Hz.  All 32-bit: the
 * largest product here is about 200 * 44100 = 8.8 million. */
static unsigned int fundamental_hz( unsigned int rate )
{
    unsigned int i, crossings = 0;
    int prev = 0;

    if (!pcm_samples) return 0;
    for (i = 0; i < pcm_samples; i++)
    {
        int v = pcm[i];
        if (prev <= 0 && v > 0) crossings++;
        prev = v;
    }
    return crossings * rate / pcm_samples;
}

/* Pull PCM until the transform says it needs more input.  Returns 0 only on a
 * hard failure; "need more input" is the normal way out. */
static int drain_output( IMFTransform *mft, DWORD out_size )
{
    MFT_OUTPUT_DATA_BUFFER out_buffer;
    IMFSample *sample;
    DWORD status;
    HRESULT hr;

    for (;;)
    {
        if (FAILED(hr = wrap_sample( &sample, NULL, 0, out_size )))
        {
            report_hr( "MFCreateSample(output) failed", hr );
            return 0;
        }
        memset( &out_buffer, 0, sizeof(out_buffer) );
        out_buffer.pSample = sample;
        status = 0;
        hr = IMFTransform_ProcessOutput( mft, 0, 1, &out_buffer, &status );
        if (SUCCEEDED(hr)) collect_pcm( sample );
        if (out_buffer.pEvents) IMFCollection_Release( out_buffer.pEvents );
        IMFSample_Release( sample );
        if (hr == MF_E_TRANSFORM_NEED_MORE_INPUT) return 1;
        if (FAILED(hr))
        {
            report_hr( "ProcessOutput failed", hr );
            return 0;
        }
        if (pcm_samples >= sizeof(pcm) / sizeof(pcm[0])) return 1;
    }
}

/* Runs one stage end to end.  Returns EXIT_PASS, EXIT_DECODE_FAILED or
 * EXIT_NOT_REGISTERED. */
static int run_stage( const struct wma_stage *st )
{
    IMFMediaType *in_type = NULL, *out_type = NULL;
    MFT_OUTPUT_STREAM_INFO out_info;
    IMFSample *sample = NULL;
    IMFTransform *mft = NULL;
    DWORD out_size;
    unsigned int hz;
    HRESULT hr;
    int rc;

    pcm_samples = 0;
    peak_abs = 0;

    WRITE_LINE( "MADEIRA-WMA: --- stage " );
    write_str( st->name );
    WRITE_LINE( " ---\n" );

    stage = "CoCreateInstance(CLSID_CWMADecMediaObject, IMFTransform)";
    hr = CoCreateInstance( &CLSID_CWMADecMediaObject, NULL, CLSCTX_INPROC_SERVER,
                           &IID_IMFTransform, (void **)&mft );
    if (FAILED(hr) || !mft)
    {
        report_hr( "no WMA decoder MFT", hr );
        WRITE_LINE( "MADEIRA-WMA: CLSID_CWMADecMediaObject is not registered, or its DLL "
                    "(wmadmod.dll -> winegstreamer.dll) is missing\n" );
        return EXIT_NOT_REGISTERED;
    }

    rc = EXIT_DECODE_FAILED;

    stage = "SetInputType";
    if (FAILED(hr = make_audio_type( &in_type, &MFAudioFormat_WMAudioV8,
                                     st->channels, st->rate, st->declared_avg_bytes,
                                     st->block_align, 16,
                                     st->extradata, st->extradata_size )))
    {
        report_hr( "MFCreateMediaType(input) failed", hr );
        goto done;
    }
    if (FAILED(hr = IMFTransform_SetInputType( mft, 0, in_type, 0 )))
    {
        report_hr( "SetInputType(WMAudioV8) failed", hr );
        goto done;
    }
    WRITE_LINE( "MADEIRA-WMA: input accepted, " );
    write_uint( st->rate );
    WRITE_LINE( " Hz " );
    write_uint( st->channels );
    WRITE_LINE( " ch, block " );
    write_uint( st->block_align );
    WRITE_LINE( ", declared " );
    write_uint( st->declared_avg_bytes );
    WRITE_LINE( " B/s\n" );

    stage = "SetOutputType";
    /* 16-bit PCM: nBlockAlign is channels * 2, nAvgBytesPerSec rate * that. */
    if (FAILED(hr = make_audio_type( &out_type, &MFAudioFormat_PCM,
                                     st->channels, st->rate,
                                     st->rate * st->channels * 2,
                                     st->channels * 2, 16, NULL, 0 )))
    {
        report_hr( "MFCreateMediaType(output) failed", hr );
        goto done;
    }
    if (FAILED(hr = IMFTransform_SetOutputType( mft, 0, out_type, 0 )))
    {
        report_hr( "SetOutputType(PCM) failed", hr );
        WRITE_LINE( "MADEIRA-WMA: the transform could not be built -- on this port that is "
                    "winegstreamer's unix side refusing the format\n" );
        goto done;
    }

    out_size = 64 * 1024;
    memset( &out_info, 0, sizeof(out_info) );
    if (SUCCEEDED(IMFTransform_GetOutputStreamInfo( mft, 0, &out_info )) && out_info.cbSize > out_size)
        out_size = out_info.cbSize;

    stage = "ProcessInput";
    if (st->probe_misaligned)
    {
        /* 1000 bytes is not a multiple of any of these block sizes. */
        if (SUCCEEDED(wrap_sample( &sample, st->data, 1000, 1000 )))
        {
            hr = IMFTransform_ProcessInput( mft, 0, sample, 0 );
            IMFSample_Release( sample );
            sample = NULL;
            WRITE_LINE( "MADEIRA-WMA: misaligned 1000-byte push returned " );
            write_hex32( (unsigned int)hr );
            WRITE_LINE( " (wma_decoder.c ignores non-multiples of block_align)\n" );
        }
    }
    {
        unsigned int pos = 0, chunk = st->push_chunk ? st->push_chunk : st->data_size;

        while (pos < st->data_size)
        {
            unsigned int n = st->data_size - pos;
            if (n > chunk) n = chunk;
            if (FAILED(hr = wrap_sample( &sample, st->data + pos, n, n )))
            {
                report_hr( "MFCreateSample(input) failed", hr );
                goto done;
            }
            IMFSample_SetSampleTime( sample, 0 );
            hr = IMFTransform_ProcessInput( mft, 0, sample, 0 );
            IMFSample_Release( sample );
            sample = NULL;
            if (hr == MF_E_NOTACCEPTING)
            {
                /* The transform wants its output drained first; that is the
                 * normal MFT handshake, so drain and retry this same chunk. */
                if (!drain_output( mft, out_size )) goto done;
                continue;
            }
            if (FAILED(hr))
            {
                report_hr( "ProcessInput failed", hr );
                goto done;
            }
            pos += n;
            if (!drain_output( mft, out_size )) goto done;
        }
    }

    stage = "ProcessOutput";
    if (!drain_output( mft, out_size )) goto done;

    stage = "checking the PCM";
    WRITE_LINE( "MADEIRA-WMA: decoded " );
    write_uint( pcm_samples );
    WRITE_LINE( " samples/channel, peak " );
    write_uint( peak_abs );
    WRITE_LINE( " of 32767\n" );

    if (pcm_samples < st->rate / 8)   /* less than an eighth of a second */
    {
        WRITE_LINE( "MADEIRA-WMA: FAIL -- too little output; the decoder produced nothing usable\n" );
        goto done;
    }
    if (peak_abs < 2000)
    {
        WRITE_LINE( "MADEIRA-WMA: FAIL -- the output is silent\n" );
        goto done;
    }

    hz = fundamental_hz( st->rate );
    WRITE_LINE( "MADEIRA-WMA: fundamental " );
    write_uint( hz );
    WRITE_LINE( " Hz (expected ~440)\n" );
    if (hz < 400 || hz > 480)
    {
        WRITE_LINE( "MADEIRA-WMA: FAIL -- that is not the 440 Hz tone that was encoded; "
                    "the transform is not decoding, it is passing bytes through\n" );
        goto done;
    }

    rc = EXIT_PASS;

done:
    stage = "cleanup";
    if (in_type) IMFMediaType_Release( in_type );
    if (out_type) IMFMediaType_Release( out_type );
    if (mft) IMFTransform_Release( mft );
    return rc;
}

static int run( void )
{
    static const struct wma_stage stages[] =
    {
        {
            "A 44100 Hz stereo, honest rate",
            wma_test_data, sizeof(wma_test_data),
            wma_test_extradata, sizeof(wma_test_extradata),
            WMA_TEST_RATE, WMA_TEST_CHANNELS, WMA_TEST_BLOCK_ALIGN, WMA_TEST_AVG_BYTES, 0, 0
        },
        {
            "B 22050 Hz stereo low bit rate, honest rate",
            wma_test_b_data, sizeof(wma_test_b_data),
            wma_test_b_extradata, sizeof(wma_test_b_extradata),
            WMA_TEST_B_RATE, WMA_TEST_B_CHANNELS, WMA_TEST_B_BLOCK_ALIGN, WMA_TEST_B_AVG_BYTES, 0, 0
        },
        {
            /* PHASE. The unix side stages pushed bytes in a FIFO and cuts
             * block_align packets off the head, so a caller that does not push
             * exactly one packet at a time must still decode identically. This
             * stage pushes two packets at a time and leads with a deliberately
             * misaligned 1000-byte buffer, which wma_decoder.c is documented to
             * ignore -- if it did not, or if the FIFO re-phased on it, the
             * fundamental check below would fail. */
            "D 22050 Hz stereo, chunked and misaligned pushes",
            wma_test_b_data, sizeof(wma_test_b_data),
            wma_test_b_extradata, sizeof(wma_test_b_extradata),
            WMA_TEST_B_RATE, WMA_TEST_B_CHANNELS, WMA_TEST_B_BLOCK_ALIGN,
            WMA_TEST_B_AVG_BYTES, WMA_TEST_B_BLOCK_ALIGN * 2, 1
        },
    };
    unsigned int i;
    HRESULT hr;
    int rc;

    stage = "CoInitializeEx";
    CoInitializeEx( NULL, COINIT_APARTMENTTHREADED );

    stage = "MFStartup";
    if (FAILED(hr = MFStartup( MF_VERSION, MFSTARTUP_LITE )))
        report_hr( "MFStartup failed (continuing)", hr );

    rc = EXIT_PASS;
    for (i = 0; i < sizeof(stages) / sizeof(stages[0]); i++)
    {
        int stage_rc = run_stage( &stages[i] );
        if (stage_rc != EXIT_PASS)
        {
            WRITE_LINE( "MADEIRA-WMA: stage " );
            write_str( stages[i].name );
            WRITE_LINE( " FAILED\n" );
            /* "not registered" is the more specific answer and outranks a
             * later stage's decode failure. */
            if (rc == EXIT_PASS || stage_rc == EXIT_NOT_REGISTERED) rc = stage_rc;
            if (stage_rc == EXIT_NOT_REGISTERED) break;
        }
    }

    if (rc == EXIT_PASS)
        WRITE_LINE( "MADEIRA-WMA: PASS -- every stage decoded WMA V2 to PCM at ~440 Hz\n" );

    MFShutdown();
    CoUninitialize();
    return rc;
}

void __cdecl start( void )
{
    DWORD id;
    HANDLE h = CreateThread( NULL, 0, watchdog, NULL, 0, &id );
    if (h) CloseHandle( h );
    ExitProcess( (UINT)run() );
}
