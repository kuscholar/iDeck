/* wma-x86.c -- does this prefix have a working WMA decoder MFT?   (MADEIRA)
 *
 * WHAT IT PROVES, AND WHY IT IS A 32-BIT PROGRAM.
 *
 * A 2008-era title playing xWMA/WMA through XAudio2 2.2 got static instead of
 * audio.  FAudio (wine/libs/faudio/src/FAudio_platform_win32_wmadec.c) decodes
 * such a voice by asking COM for the Windows WMA decoder MFT:
 *
 *     CoCreateInstance( CLSID_CWMADecMediaObject, ..., IID_IMFTransform, ... )
 *
 * In Wine that CLSID is wmadmod.dll, which forwards to CLSID_wg_wma_decoder
 * {5b4d4e54-...} in winegstreamer.dll, whose decoder is a GStreamer pipeline
 * on the unix side.  There is no GStreamer on iOS, so winegstreamer.dll was
 * not built at all and the device log read:
 *
 *     err:module:load_dll [dll-missing] L"C:\windows\system32\winegstreamer.dll"
 *     err:ole:com_get_class_object no class object {5b4d4e54-...}
 *     fixme:ole:CoCreateInstanceEx no instance created for interface
 *         {bf94c121-...} (IMFTransform) of class {2eeb4adf-...}, hr 0x80070005
 *
 * -- and FAudio, given no decoder, submitted the COMPRESSED bytes to the mixer
 * as if they were PCM.  This test walks that exact chain: CoCreateInstance for
 * IMFTransform, a WMA V2 input type, a 16-bit PCM output type, one
 * ProcessInput of real WMA packets, and ProcessOutput until the transform runs
 * dry.  It then checks the PCM actually came back as AUDIO: non-silent, and
 * with the 440 Hz fundamental the packets were encoded from.  A decoder that
 * "works" but hands back the input unchanged fails that second check, which is
 * the whole point -- passing the bytes through is precisely the bug.
 *
 * It is i386 because that is the bitness of the title, and because the unix
 * side it exercises (build/ntdll-unix/winegstreamer_unixlib_ios.c) reaches it
 * through the wow64 half of its unix call table -- a different set of
 * parameter-block layouts from the 64-bit half.  Running it 64-bit would
 * test the other table.
 *
 * THREE STAGES:
 *
 *   A  44100 Hz stereo, honest parameters.  The baseline.
 *   B  22050 Hz stereo at a low bit rate -- the geometry of a stream that
 *      failed on device (that one was 22050 Hz stereo, block_align 1487).
 *   D  B's bytes, pushed in chunks and after a misaligned buffer.
 *
 * There is no stage C any more.  It declared B's bytes with a WRONG average
 * byte rate (the 48 kbit/s figure libavformat/xwma.c lists as an xWMA lie) and
 * expected the unix side's bit-rate retry to rescue it.  That retry can only
 * work for a bit-reservoir (superframe) stream, whose packets say how many
 * frames they hold; FFmpeg's encoder writes single-frame packets (flags2 = 1),
 * and a single-frame packet decoded at the wrong rate is wrong audio, not a
 * detectable failure.  xWMA streams are always superframe streams, so the
 * stage tested a case that does not occur.  tests/host/
 * check-wma-decoder.py covers WMA v1 and v2 at many more geometries.
 *
 * THE TEST VECTORS are 0.5 s of a 440 Hz sine at half full scale, encoded by a
 * host FFmpeg 7.1.1 wmav2 encoder, with the codec-private bytes that encoder
 * produced going in MF_MT_USER_DATA.  They are embedded rather than loaded
 * from disk so the test has no dependency on the prefix's filesystem.
 *
 * HOW TO RUN IT: tests/x86/build-wma-test.sh copies it into
 * app/Madeira/i386-windows/; launch it directly with
 * env.MADEIRA_EXE = wma-x86.exe in madeira.cfg, which runs it from
 * C:\windows\syswow64 (this needs the WoW64 launch path and an i386 build
 * tree with winegstreamer.dll and wmadmod.dll).
 *
 * Deliberate restrictions, so the test depends only on the DLLs it names:
 * no CRT (this file supplies `start' and is linked -nostdlib), no
 * 64-bit division, no int-to-double conversion.
 *
 * Exit status (the process exit code):
 *   62  PASS -- every stage created the MFT, negotiated both types, and
 *       returned PCM that is non-silent and has a ~440 Hz fundamental
 *   63  the MFT was created but a stage failed: a type was rejected, no
 *       output came back, or the output was silence / the wrong frequency
 *   64  the class is not registered (or its DLL is missing) -- this is the
 *       failure the port had before winegstreamer.dll was built
 *   65  ten seconds elapsed with the run unfinished; the last line printed
 *       says which stage it died in
 */
